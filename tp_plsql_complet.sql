-- Question 5.1 — AFTER, :OLD seulement au DELETE
CREATE OR REPLACE TRIGGER trg_clients_journal
AFTER INSERT OR UPDATE OR DELETE ON clients
FOR EACH ROW
DECLARE
    v_operation journal.operation%TYPE;
    v_ligne_id  journal.ligne_id%TYPE;
BEGIN
    IF INSERTING THEN
        v_operation := 'INSERT';
        v_ligne_id  := :NEW.id;
    ELSIF UPDATING THEN
        v_operation := 'UPDATE';
        v_ligne_id  := :NEW.id;
    ELSIF DELETING THEN
        v_operation := 'DELETE';
        v_ligne_id  := :OLD.id;
    END IF;

    INSERT INTO journal (table_nom, operation, ligne_id, utilisateur)
    VALUES ('CLIENTS', v_operation, v_ligne_id, USER);
END trg_clients_journal;
/
