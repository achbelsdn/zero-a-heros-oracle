-- Question 4.1 — quatre lignes, erreur -20020 si client absent
CREATE OR REPLACE PROCEDURE sp_afficher_client(p_id IN NUMBER) IS
    v_nom   clients.nom%TYPE;
    v_email clients.email%TYPE;
BEGIN
    SELECT nom, email INTO v_nom, v_email
    FROM clients
    WHERE id = p_id;

    DBMS_OUTPUT.PUT_LINE('Nom : ' || v_nom || ' | Email : ' || v_email);
    DBMS_OUTPUT.PUT_LINE('Nombre de commandes : ' || fn_nb_commandes(p_id));
    DBMS_OUTPUT.PUT_LINE('Total : ' || fn_total_client(p_id));
    DBMS_OUTPUT.PUT_LINE('Statut : ' || fn_statut_client(p_id));
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20020, 'Client inconnu');
END sp_afficher_client;
