-- Question 3.3 — 0 s'il n'y a aucune commande (sinon SUM renverrait NULL)
CREATE OR REPLACE FUNCTION fn_total_client(p_client_id IN NUMBER)
RETURN NUMBER IS
    v_total NUMBER;
BEGIN
    SELECT NVL(SUM(montant), 0) INTO v_total
    FROM commandes
    WHERE client_id = p_client_id;

    RETURN v_total;
END fn_total_client;
/
