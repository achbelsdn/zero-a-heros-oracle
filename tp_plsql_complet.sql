-- Question 3.4 — reutilise fn_total_client
CREATE OR REPLACE FUNCTION fn_statut_client(p_client_id IN NUMBER)
RETURN VARCHAR2 IS
    v_total NUMBER;
BEGIN
    v_total := fn_total_client(p_client_id);

    IF v_total >= 150000 THEN
        RETURN 'VIP';
    ELSIF v_total >= 50000 THEN
        RETURN 'Regulier';
    ELSE
        RETURN 'Occasionnel';
    END IF;
END fn_statut_client;
