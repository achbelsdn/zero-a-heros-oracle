-- Question 4.2 — prochain id = MAX + 1, date du jour sans l'heure, pas de COMMIT
CREATE OR REPLACE PROCEDURE sp_ajouter_client(
    p_nom   IN  VARCHAR2,
    p_email IN  VARCHAR2,
    p_id    OUT NUMBER
) IS
BEGIN
    SELECT NVL(MAX(id), 0) + 1 INTO p_id FROM clients;

    INSERT INTO clients (id, nom, email, date_inscription)
    VALUES (p_id, p_nom, p_email, TRUNC(SYSDATE));
END sp_ajouter_client;
