-- Question 3.5
CREATE OR REPLACE FUNCTION fn_nom_categorie(p_produit_id IN NUMBER)
RETURN VARCHAR2 IS
    v_nom categories.nom%TYPE;
BEGIN
    SELECT c.nom INTO v_nom
    FROM produits p
    JOIN categories c ON c.id = p.categorie_id
    WHERE p.id = p_produit_id;

    RETURN v_nom;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'Inconnu';
END fn_nom_categorie;
/
SHOW ERRORS

