-- Question 5.3 — BEFORE INSERT sur la ligne : controle puis decrement
CREATE OR REPLACE TRIGGER trg_lignes_stock
BEFORE INSERT ON commande_produits
FOR EACH ROW
DECLARE
    v_stock produits.stock%TYPE;
BEGIN
    SELECT stock INTO v_stock
    FROM produits
    WHERE id = :NEW.produit_id
    FOR UPDATE;

    IF NVL(v_stock, 0) < :NEW.quantite THEN
        RAISE_APPLICATION_ERROR(-20031, 'Stock insuffisant');
    END IF;

    UPDATE produits
    SET stock = stock - :NEW.quantite
    WHERE id = :NEW.produit_id;
END trg_lignes_stock;
/
SHOW ERRORS

