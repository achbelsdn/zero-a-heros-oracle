-- Question 4.5 — une ligne par mois de l'annee qui a des commandes
CREATE OR REPLACE PROCEDURE sp_rapport_mensuel(p_annee IN NUMBER) IS
BEGIN
    FOR r IN (
        SELECT TO_CHAR(date_commande, 'MM') AS mois,
               COUNT(*)                     AS nb,
               NVL(SUM(montant), 0)         AS ca
        FROM commandes
        WHERE EXTRACT(YEAR FROM date_commande) = p_annee
        GROUP BY TO_CHAR(date_commande, 'MM')
        ORDER BY TO_CHAR(date_commande, 'MM')
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('Mois ' || r.mois || ' : ' || r.nb
                             || ' commande(s), CA = ' || r.ca);
    END LOOP;
END sp_rapport_mensuel;
/
SHOW ERRORS

