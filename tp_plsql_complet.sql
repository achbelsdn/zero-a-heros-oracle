-- Question 4.3
CREATE OR REPLACE PROCEDURE sp_recalculer_montant(p_commande_id IN NUMBER) IS
    v_existe  NUMBER;
    v_montant NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe
    FROM commandes
    WHERE id = p_commande_id;

    IF v_existe = 0 THEN
        RAISE_APPLICATION_ERROR(-20021, 'Commande inconnue');
    END IF;

    SELECT NVL(SUM(p.prix * cp.quantite), 0) INTO v_montant
    FROM commande_produits cp
    JOIN produits p ON p.id = cp.produit_id
    WHERE cp.commande_id = p_commande_id;

    UPDATE commandes
    SET montant = v_montant
    WHERE id = p_commande_id;
END sp_recalculer_montant;
/
SHOW ERRORS

